const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
let stored = null;
const localStorage = {getItem:()=>stored,setItem:(_,value)=>{stored=value;}};
const exported = {};
const context=vm.createContext({exports:exported,localStorage,WeakMap,Set,JSON,Error});
const source=ts.transpileModule(fs.readFileSync('src/state/appStore.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
vm.runInContext(source,context);
const defaults=()=>({players:[],settings:{currentGameNumber:0,currentSessionNumber:0},activeSession:null,pastSessions:[]});
let notifications=0;
const unsubscribe=exported.subscribe(()=>notifications++);
const a=exported.readStoredData(d=>d,defaults);
const b=exported.readStoredData(d=>d,defaults);
a.settings.currentGameNumber=1;
assert.equal(exported.writeStoredData(a),true);
assert.throws(()=>exported.writeStoredData(b),/changed in another tab/);
assert.equal(notifications,1);
unsubscribe();
assert.equal(JSON.parse(stored).settings.currentGameNumber,1);
const once=exported.readStoredData(d=>({...d,schemaVersion:2}),defaults);
exported.writeStoredData(once);
const twice=exported.readStoredData(d=>({...d,schemaVersion:2}),defaults);
assert.equal(JSON.stringify(once),JSON.stringify(twice));
console.log('PASS: migrated store rejects stale writes, notifies subscribers, preserves records and idempotent normalization');
